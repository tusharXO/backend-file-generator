test("unexpected errors return a generic 500 response and are logged internally", () => {
  const source = generateErrorMiddleware();
  const logs = [];
  const result = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } });
  const module = { exports: {} };
  new Function("exports", "console", result.outputText)(module.exports, { error: error => logs.push(error) });
  let status;
  let body;
  const error = new Error("private database address");
  module.exports.errorHandler(error, {}, { status(value) { status = value; return this; }, json(value) { body = value; } }, () => assert.fail("unexpected next"));
  assert.equal(status, 500);
  assert.deepEqual(body, { error: "Internal server error" });
  assert.deepEqual(logs, [error]);
});

test("generated health checks use the shared Prisma client and shutdown disconnects it", async t => {
  let server;
  let offline = false;
  let queries = 0;
  const signals = new Map();
  let disconnected;
  const closedDatabase = new Promise(resolve => { disconnected = resolve; });
  const expressFactory = Object.assign(() => {
    const app = express();
    const listen = app.listen.bind(app);
    app.listen = (...args) => { server = listen(...args); return server; };
    return app;
  }, express);
  execute(generateServer("", ""), {
    express: expressFactory,
    "./lib/prisma.js": {
      prisma: { $queryRaw: async () => { queries++; if (offline) throw new Error("offline"); return [1]; } },
      disconnectDatabase: async () => { disconnected(); },
    },
    "./middleware/error-handler.js": execute(generateErrorMiddleware()),
  }, {
    process: { env: { PORT: 0 }, once: (signal, callback) => signals.set(signal, callback), exit: () => assert.fail("forced shutdown") },
    console: { log() {}, error() {} },
  });
  t.after(() => server.listening ? new Promise(resolve => server.close(resolve)) : undefined);
  await new Promise(resolve => server.once("listening", resolve));
  const url = `http://127.0.0.1:${server.address().port}/health`;
  const connected = await fetch(url);
  assert.equal(connected.status, 200);
  assert.deepEqual(await connected.json(), { status: "ok", database: "connected" });
  offline = true;
  const unavailable = await fetch(url);
  assert.equal(unavailable.status, 503);
  assert.deepEqual(await unavailable.json(), { status: "error", database: "disconnected" });
  assert.equal(queries, 2);
  signals.get("SIGTERM")();
  await closedDatabase;
  assert.equal(server.listening, false);
});
