test("string primary keys are supplied on create, constrained in URLs, and immutable on update", () => {
  const definition = { name: "Item", primaryKey: "sku", fields: [field("sku", "string", { minLength: 2, maxLength: 6 }), field("name", "string")] };
  const schemas = execute(generateValidationSchema(definition));
  assert.deepEqual(schemas.ItemCreateSchema.parse({ sku: "SKU-1", name: "Item" }), { sku: "SKU-1", name: "Item" });
  assert.equal(schemas.ItemCreateSchema.safeParse({ name: "Item" }).success, false);
  assert.equal(schemas.ItemUpdateSchema.safeParse({ sku: "other" }).success, false);
  assert.equal(schemas.ItemIdSchema.parse("SKU-1"), "SKU-1");
  for (const id of ["", "x", "too-long", 1]) assert.equal(schemas.ItemIdSchema.safeParse(id).success, false);
  definition.fields[0].minLength = 0;
  assert.equal(execute(generateValidationSchema(definition)).ItemIdSchema.safeParse("").success, false);
});

async function startApp(t, definition, delegate, options = {}) {
  const variable = definition.name[0].toLowerCase() + definition.name.slice(1);
  const schemaPath = `../validation/${variable}.schema.js`;
  const schemas = execute(generateValidationSchema(definition));
  const middleware = execute(generateValidationMiddleware(definition), { [schemaPath]: schemas });
  const service = execute(generateService(definition), { "../lib/prisma.js": { prisma: { [variable]: delegate } } });
  const apis = [
    ["GET", "list", "/records"], ["POST", "create", "/records"],
    ["GET", "get", `/records/:${definition.primaryKey}`],
    ["PUT", "update", `/records/:${definition.primaryKey}`],
    ["DELETE", "delete", `/records/:${definition.primaryKey}`],
  ].map(([method, operation, path]) => ({ name: operation, method, operation, path, entity: definition.name }));
  const { default: router } = execute(generateRoute(definition, apis), {
    [schemaPath]: schemas,
    [`../middleware/${variable}.validation.js`]: middleware,
    [`../services/${variable}.service.js`]: service,
  });
  const { errorHandler } = execute(generateErrorMiddleware());
  const app = express();
  app.use(express.json(options));
  app.use(router);
  app.use(errorHandler);
  const server = await new Promise(resolve => {
    const listener = app.listen(0, "127.0.0.1", () => resolve(listener));
  });
  t.after(() => new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve())));
  return async (method, path, body, raw = false) => {
    const response = await fetch(`http://127.0.0.1:${server.address().port}${path}`, {
      method, headers: { "content-type": "application/json" },
      ...(body === undefined ? {} : { body: raw ? body : JSON.stringify(body) }),
    });
    const text = await response.text();
    return { status: response.status, body: text ? JSON.parse(text) : null };
  };
}

test("generated CRUD routes validate before DB access and preserve successful CRUD responses", async t => {
  const calls = [];
  const delegate = {
    findMany: async () => { calls.push("list"); return [{ id: 1 }]; },
    findUnique: async query => { calls.push(query); return query.where.id === 404 ? null : { id: query.where.id }; },
    create: async query => { calls.push(query); return { id: 1, ...query.data }; },
    update: async query => { calls.push(query); return { id: query.where.id, ...query.data }; },
    delete: async query => { calls.push(query); return { id: query.where.id }; },
  };
  const request = await startApp(t, entity(), delegate);
  for (const method of ["GET", "PUT", "DELETE"]) {
    assert.equal((await request(method, "/records/abc", method === "PUT" ? { name: "Updated" } : undefined)).status, 400);
  }
  assert.equal((await request("POST", "/records", { ...payload(), id: 2 })).status, 400);
  assert.equal((await request("PUT", "/records/1", {})).status, 400);
  assert.equal(calls.length, 0);
  assert.deepEqual(await request("GET", "/records"), { status: 200, body: [{ id: 1 }] });
  assert.deepEqual(await request("GET", "/records/1"), { status: 200, body: { id: 1 } });
  assert.equal((await request("GET", "/records/404")).status, 404);
  assert.deepEqual(await request("POST", "/records", payload()), { status: 201, body: { id: 1, ...payload() } });
  assert.deepEqual(await request("PUT", "/records/1", { name: "Updated" }), { status: 200, body: { id: 1, name: "Updated" } });
  assert.deepEqual(await request("DELETE", "/records/1"), { status: 204, body: null });
  assert.deepEqual(calls.at(-1), { where: { id: 1 } });
});

test("generated string ID routes send strings to Prisma without numeric coercion", async t => {
  const definition = { name: "Item", primaryKey: "sku", fields: [field("sku", "string", { minLength: 2, maxLength: 12 }), field("name", "string")] };
  const calls = [];
  const delegate = {
    findUnique: async query => { calls.push(query); return { sku: query.where.sku }; },
    create: async query => { calls.push(query); return query.data; },
  };
  const request = await startApp(t, definition, delegate);
  assert.deepEqual(await request("GET", "/records/SKU-42"), { status: 200, body: { sku: "SKU-42" } });
  assert.deepEqual(calls[0], { where: { sku: "SKU-42" } });
  assert.equal((await request("POST", "/records", { name: "Missing key" })).status, 400);
  assert.deepEqual(await request("POST", "/records", { sku: "SKU-42", name: "Item" }), { status: 201, body: { sku: "SKU-42", name: "Item" } });
});

test("central middleware maps Prisma conflicts and absent records without leaking internals", async t => {
  const delegate = {
    create: async () => { throw Object.assign(new Error("secret database details"), { code: "P2002", meta: { target: ["name"] } }); },
    update: async () => { throw Object.assign(new Error("secret update details"), { code: "P2025" }); },
    delete: async () => { throw Object.assign(new Error("secret delete details"), { code: "P2025" }); },
  };
  const request = await startApp(t, entity(), delegate);
  const conflict = await request("POST", "/records", payload());
  assert.equal(conflict.status, 409);
  assert.doesNotMatch(JSON.stringify(conflict.body), /secret|target|P2002/);
  for (const method of ["PUT", "DELETE"]) {
    const result = await request(method, "/records/1", method === "PUT" ? { name: "Updated" } : undefined);
    assert.deepEqual(result, { status: 404, body: { error: "Record not found" } });
  }
});

