import type { ProjectDefinition } from "@backend-file-generator/shared";

/** Emit a dependency-free HTTP check that can run on the host or in a container. */
export function generateSmokeTest(project: ProjectDefinition): string {
  return `import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import test from "node:test";

const definition = ${JSON.stringify(project, null, 2)};
` + String.raw`
const baseUrl = process.env.API_URL || "http://127.0.0.1:3000";

async function request(method, route, body) {
  const response = await fetch(new URL(route, baseUrl), {
    method,
    ...(body === undefined ? {} : {
      headers: { "content-type": "application/json" },
      body: JSON.stringify(body),
    }),
    signal: AbortSignal.timeout(10000),
  });
  const text = await response.text();
  return { status: response.status, body: text ? JSON.parse(text) : undefined };
}

function expectStatus(response, expected) {
  assert.equal(response.status, expected, JSON.stringify(response.body));
}

function valueFor(field, nonce) {
  switch (field.type) {
    case "string": {
      const value = (nonce + "-" + field.name).padEnd(field.minLength || 1, "x");
      return field.maxLength === undefined ? value : value.slice(0, field.maxLength);
    }
    case "integer": return 12;
    case "number": return 12.5;
    case "boolean": return true;
    case "date": return "2026-10-30";
    case "datetime": return "2026-10-30T10:00:00Z";
    default: throw new Error("Unsupported test field: " + field.type);
  }
}

test("health reports a connected database", { timeout: 15000 }, async () => {
  const health = await request("GET", "/health");
  expectStatus(health, 200);
  assert.equal(health.body.database, "connected");
});

for (const entity of definition.entities) {
  const apis = definition.apis.filter(api => api.entity === entity.name);
  if (!apis.length) continue;
  test("declared CRUD APIs for " + entity.name, { timeout: 60000 }, async () => {
    const api = operation => apis.find(candidate => candidate.operation === operation);
    if (!api("create")) {
      if (api("list")) expectStatus(await request("GET", api("list").path), 200);
      return;
    }

    const nonce = randomUUID().replaceAll("-", "");
    const key = entity.fields.find(field => field.name === entity.primaryKey);
    const payload = {};
    for (const field of entity.fields) {
      if (field.autoGenerated || (field.name === entity.primaryKey && field.type === "integer")) continue;
      if (field.defaultValue === undefined && (field.required || field.name === entity.primaryKey)) {
        payload[field.name] = valueFor(field, nonce);
      }
    }

    let id;
    let removed = false;
    const itemPath = operation => api(operation).path.replace(
      ":" + entity.primaryKey, encodeURIComponent(String(id))
    );
    try {
      const created = await request("POST", api("create").path, payload);
      expectStatus(created, 201);
      id = created.body[entity.primaryKey];
      assert.notEqual(id, undefined);
      if (key.type === "string") assert.equal(id, payload[entity.primaryKey]);
      else assert.ok(Number.isInteger(id) && id > 0);

      for (const field of entity.fields) {
        if (field.defaultValue !== undefined) assert.equal(created.body[field.name], field.defaultValue);
        if (field.autoGenerated) assert.ok(Number.isFinite(Date.parse(created.body[field.name])));
        if (!field.required && field.nullable && field.defaultValue === undefined) {
          assert.equal(created.body[field.name], null);
        }
      }

      // Unknown properties are always invalid, even if every writable field is optional.
      expectStatus(await request("POST", api("create").path, { ...payload, "__bfg_unknown": true }), 400);

      const hasUniqueInput = key.type === "string" || entity.fields.some(field =>
        field.unique && field.name !== entity.primaryKey && payload[field.name] !== undefined && payload[field.name] !== null
      );
      if (hasUniqueInput) expectStatus(await request("POST", api("create").path, payload), 409);

      if (api("list")) {
        const listed = await request("GET", api("list").path);
        expectStatus(listed, 200);
        assert.ok(listed.body.some(record => record[entity.primaryKey] === id));
      }
      if (api("get")) {
        const found = await request("GET", itemPath("get"));
        expectStatus(found, 200);
        assert.equal(found.body[entity.primaryKey], id);
        if (key.type === "integer") {
          const invalidPath = api("get").path.replace(":" + entity.primaryKey, "not-an-integer");
          expectStatus(await request("GET", invalidPath), 400);
        }
      }

      let updateBody;
      if (api("update")) {
        expectStatus(await request("PUT", itemPath("update"), {}), 400);
        const mutable = entity.fields.filter(field => field.name !== entity.primaryKey && !field.autoGenerated);
        if (mutable.length) {
          updateBody = Object.fromEntries(mutable.map(field => [field.name, valueFor(field, "updated" + nonce)]));
          const updated = await request("PUT", itemPath("update"), updateBody);
          expectStatus(updated, 200);
          for (const field of mutable) {
            const expected = field.type === "date" || field.type === "datetime"
              ? new Date(updateBody[field.name]).toISOString() : updateBody[field.name];
            assert.equal(updated.body[field.name], expected);
          }
          for (const field of entity.fields.filter(field => field.autoGenerated)) {
            if (field.autoGenerated === "createdAt") assert.equal(updated.body[field.name], created.body[field.name]);
            else assert.ok(Date.parse(updated.body[field.name]) >= Date.parse(created.body[field.name]));
          }
          const nullable = mutable.find(field => field.nullable);
          if (nullable) {
            const cleared = await request("PUT", itemPath("update"), { [nullable.name]: null });
            expectStatus(cleared, 200);
            assert.equal(cleared.body[nullable.name], null);
          }
        }
      }

      if (api("delete")) {
        expectStatus(await request("DELETE", itemPath("delete")), 204);
        removed = true;
        if (api("get")) expectStatus(await request("GET", itemPath("get")), 404);
        if (updateBody) expectStatus(await request("PUT", itemPath("update"), updateBody), 404);
        expectStatus(await request("DELETE", itemPath("delete")), 404);
      } else {
        console.log("No DELETE API for " + entity.name + "; test record " + id + " remains in the development database.");
      }
    } finally {
      // Cleanup is limited to a record this test created, never pre-existing rows.
      if (id !== undefined && !removed && api("delete")) {
        await request("DELETE", itemPath("delete")).catch(() => {});
      }
    }
  });
}
`;
}
