import type { EntityDefinition, FieldDefinition } from "@backend-file-generator/shared";

function fieldSchema(field: FieldDefinition, primaryKey = false): string {
  let schema: string;
  switch (field.type) {
    case "string":
      schema = "z.string()";
      if (primaryKey || field.minLength !== undefined) {
        schema += `.min(${Math.max(primaryKey ? 1 : 0, field.minLength ?? 0)})`;
      }
      if (field.maxLength !== undefined) schema += `.max(${field.maxLength})`;
      break;
    case "integer":
      schema = "z.number().int().min(-2147483648).max(2147483647)";
      break;
    case "number":
      schema = "z.number()";
      break;
    case "boolean":
      schema = "z.boolean()";
      break;
    case "date":
      schema = 'z.iso.date().transform(value => new Date(`${value}T00:00:00.000Z`))';
      break;
    case "datetime":
      schema = "z.iso.datetime({ offset: true }).transform(value => new Date(value))";
      break;
  }
  return schema + (field.nullable ? ".nullable()" : "");
}

export function generateValidationSchema(entity: EntityDefinition): string {
  const primaryKey = entity.fields.find(field => field.name === entity.primaryKey);
  if (!primaryKey) throw new Error(`Missing primary key for ${entity.name}`);
  const mutableFields = entity.fields.filter(field => field.name !== entity.primaryKey && !field.autoGenerated);
  const createFields = entity.fields
    .filter(field => !field.autoGenerated && (field.name !== entity.primaryKey || field.type === "string"))
    .map(field => {
      let schema = fieldSchema(field, field.name === entity.primaryKey);
      if (!field.required || field.defaultValue !== undefined) schema += ".optional()";
      return `  ${field.name}: ${schema}`;
    });
  const updateFields = mutableFields.map(field => `  ${field.name}: ${fieldSchema(field)}.optional()`);
  const idSchema = primaryKey.type === "integer"
    ? 'z.string().regex(/^[1-9]\\d*$/, "Expected a positive integer ID").transform(Number).pipe(z.number().int().min(1).max(2147483647))'
    : fieldSchema(primaryKey, true);
  return `import { z } from "zod";

export const ${entity.name}IdSchema = ${idSchema};

export const ${entity.name}CreateSchema = z.strictObject({
${createFields.join(",\n")}
});

export const ${entity.name}UpdateSchema = z.strictObject({
${updateFields.join(",\n")}
}).refine(value => Object.keys(value).length > 0, {
  message: "Provide at least one field to update"
});

export type ${entity.name}Id = z.infer<typeof ${entity.name}IdSchema>;
export type ${entity.name}CreateInput = z.infer<typeof ${entity.name}CreateSchema>;
export type ${entity.name}UpdateInput = z.infer<typeof ${entity.name}UpdateSchema>;
`;
}
