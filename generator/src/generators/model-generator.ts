import type { EntityDefinition, FieldType } from "@backend-file-generator/shared";

const prismaTypes: Record<FieldType, string> = {
  string: "String", integer: "Int", number: "Float", boolean: "Boolean",
  date: "DateTime", datetime: "DateTime",
};

function defaultLiteral(value: string | number | boolean): string {
  if (typeof value !== "number") return JSON.stringify(value);
  const [coefficient, exponent] = value.toString().split("e");
  if (exponent === undefined) return coefficient;

  // Prisma requires plain decimal literals. Shift the decimal point without
  // arithmetic so every digit of JavaScript's round-trip representation survives.
  const sign = coefficient.startsWith("-") ? "-" : "";
  const magnitude = sign ? coefficient.slice(1) : coefficient;
  const digits = magnitude.replace(".", "");
  const point = (magnitude.includes(".") ? magnitude.indexOf(".") : magnitude.length) + Number(exponent);
  if (point <= 0) return `${sign}0.${"0".repeat(-point)}${digits}`;
  if (point >= digits.length) return `${sign}${digits}${"0".repeat(point - digits.length)}`;
  return `${sign}${digits.slice(0, point)}.${digits.slice(point)}`;
}

export function generatePrismaModel(entity: EntityDefinition): string {
  const fields = entity.fields.map(field => {
    const attributes: string[] = [];
    if (field.name === entity.primaryKey) {
      attributes.push("@id");
      if (field.type === "integer") attributes.push("@default(autoincrement())");
    } else if (field.unique) {
      attributes.push("@unique");
    }
    if (field.autoGenerated) {
      attributes.push("@default(now())");
      if (field.autoGenerated === "updatedAt") attributes.push("@updatedAt");
    } else if (field.defaultValue !== undefined) {
      attributes.push(`@default(${defaultLiteral(field.defaultValue)})`);
    }
    return `  ${field.name} ${prismaTypes[field.type]}${field.nullable ? "?" : ""} ${attributes.join(" ")}`.trimEnd();
  });
  return [`model ${entity.name} {`, ...fields, "}"].join("\n");
}
