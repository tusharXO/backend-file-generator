export interface ValidationResult {
  valid: boolean;
  errors: string[];
}

type RecordValue = Record<string, unknown>;

const fieldTypes = new Set(["string", "integer", "number", "boolean", "date", "datetime"]);
const operationMethods: Record<string, string> = {
  list: "GET",
  get: "GET",
  create: "POST",
  update: "PUT",
  delete: "DELETE",
};
const reservedIdentifiers = new Set([
  "abstract", "any", "as", "async", "await", "bigint", "boolean", "break",
  "case", "catch", "class", "const", "constructor", "continue", "debugger",
  "declare", "default", "delete", "do", "else", "enum", "eval", "export",
  "extends", "false", "finally", "for", "from", "function", "get", "global",
  "if", "implements", "import", "in", "infer", "instanceof", "interface",
  "is", "keyof", "let", "module", "namespace", "never", "new", "null",
  "number", "object", "of", "package", "private", "protected", "prototype",
  "public", "readonly", "require", "return", "set", "static", "string",
  "super", "switch", "symbol", "this", "throw", "true", "try", "type",
  "typeof", "undefined", "unique", "unknown", "var", "void", "while",
  "with", "yield", "tostring", "valueof", "hasownproperty", "isprototypeof",
  "propertyisenumerable", "tolocalestring",
]);
const reservedModelNames = new Set([
  "int", "float", "datetime", "bytes", "json", "bigint", "boolean", "string",
  "prisma", "prismaclient", "prismapromise", "transactionclient", "decimal",
  "dbnull", "jsonnull", "anynull", "jsonvalue", "inputjsonvalue", "batchpayload",
  "loglevel", "logevent", "queryevent", "errorformat", "middleware", "sql",
  "datasource", "generator", "model", "view", "req", "res", "id",
  "con", "prn", "aux", "nul",
]);

function isRecord(value: unknown): value is RecordValue {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function has(value: RecordValue, key: string): boolean {
  return Object.prototype.hasOwnProperty.call(value, key);
}

function checkKeys(value: RecordValue, allowed: string[], label: string, errors: string[]): void {
  for (const key of Object.keys(value)) {
    if (!allowed.includes(key)) {
      errors.push(`${label}.${key} is not supported.`);
    }
  }
}

function isNonemptyString(value: unknown): value is string {
  return typeof value === "string" && value.trim().length > 0 && value === value.trim();
}

function checkIdentifier(value: unknown, label: string, errors: string[], model = false): value is string {
  if (typeof value !== "string" || !/^[A-Za-z][A-Za-z0-9_]{0,62}$/.test(value)) {
    errors.push(`${label} must be an identifier of 1–63 letters, digits, or underscores, starting with a letter.`);
    return false;
  }

  const normalized = value.toLowerCase();
  if (reservedIdentifiers.has(normalized) || (model && (reservedModelNames.has(normalized) || /^(?:com|lpt)[1-9]$/.test(normalized)))) {
    errors.push(`${label} uses reserved identifier "${value}".`);
    return false;
  }

  return true;
}

function checkDefault(field: RecordValue, label: string, errors: string[]): void {
  if (!has(field, "defaultValue")) {
    return;
  }

  const value = field.defaultValue;
  const matches = field.type === "string" ? typeof value === "string"
    : field.type === "boolean" ? typeof value === "boolean"
    : field.type === "integer" ? typeof value === "number" && Number.isInteger(value) && value >= -2147483648 && value <= 2147483647
    : field.type === "number" ? typeof value === "number" && Number.isFinite(value)
    : false;

  if (!matches) {
    errors.push(`${label}.defaultValue must match its supported primitive field type; date defaults are not supported.`);
    return;
  }

  if (typeof value === "string") {
    if (typeof field.minLength === "number" && value.length < field.minLength) {
      errors.push(`${label}.defaultValue is shorter than minLength.`);
    }
    if (typeof field.maxLength === "number" && value.length > field.maxLength) {
      errors.push(`${label}.defaultValue is longer than maxLength.`);
    }
  }
}

function checkField(field: RecordValue, label: string, primaryKey: unknown, errors: string[]): void {
  checkKeys(field, ["name", "type", "required", "unique", "nullable", "minLength", "maxLength", "defaultValue", "autoGenerated"], label, errors);
  checkIdentifier(field.name, `${label}.name`, errors);
  if (typeof field.type !== "string" || !fieldTypes.has(field.type)) {
    errors.push(`${label}.type must be string, integer, number, boolean, date, or datetime.`);
  }

  for (const key of ["required", "unique", "nullable"]) {
    if (typeof field[key] !== "boolean") {
      errors.push(`${label}.${key} must be a boolean.`);
    }
  }

  for (const key of ["minLength", "maxLength"]) {
    if (has(field, key)) {
      if (field.type !== "string") {
        errors.push(`${label}.${key} is supported only for string fields.`);
      }
      if (typeof field[key] !== "number" || !Number.isSafeInteger(field[key]) || field[key] < 0) {
        errors.push(`${label}.${key} must be a nonnegative safe integer.`);
      }
    }
  }
  if (typeof field.minLength === "number" && typeof field.maxLength === "number" && field.minLength > field.maxLength) {
    errors.push(`${label}.minLength must not exceed maxLength.`);
  }

  checkDefault(field, label, errors);

  if (has(field, "autoGenerated")) {
    if (field.autoGenerated !== "createdAt" && field.autoGenerated !== "updatedAt") {
      errors.push(`${label}.autoGenerated must be createdAt or updatedAt.`);
    }
    if (field.type !== "date" && field.type !== "datetime") {
      errors.push(`${label}.autoGenerated requires a date or datetime field.`);
    }
    if (field.nullable !== false) {
      errors.push(`${label}.autoGenerated fields must be nonnullable.`);
    }
    if (has(field, "defaultValue")) {
      errors.push(`${label} cannot combine autoGenerated with defaultValue.`);
    }
  }

  if (field.name === primaryKey) {
    if (field.type !== "integer" && field.type !== "string") {
      errors.push(`${label}: primary keys support only integer autoincrement or client-supplied string values.`);
    }
    if (field.type === "string" && field.maxLength === 0) {
      errors.push(`${label}: string primary keys require maxLength of at least 1 because IDs must be nonempty.`);
    }
    if (field.required !== true || field.nullable !== false) {
      errors.push(`${label}: primary keys must be required and nonnullable.`);
    }
    if (has(field, "defaultValue") || has(field, "autoGenerated")) {
      errors.push(`${label}: primary keys cannot specify defaultValue or autoGenerated.`);
    }
  } else if (field.required === false && field.nullable === false && !has(field, "defaultValue") && !has(field, "autoGenerated")) {
    errors.push(`${label}: an optional nonnullable field requires defaultValue.`);
  }
}

function checkEntities(entities: unknown[], errors: string[]): Map<string, RecordValue> {
  const names = new Set<string>();
  const result = new Map<string, RecordValue>();

  entities.forEach((entity, index) => {
    const label = `entities[${index}]`;
    if (!isRecord(entity)) {
      errors.push(`${label} must be an object.`);
      return;
    }
    checkKeys(entity, ["name", "fields", "primaryKey"], label, errors);
    if (checkIdentifier(entity.name, `${label}.name`, errors, true)) {
      if (names.has(entity.name.toLowerCase())) {
        errors.push(`Duplicate entity name: ${entity.name} (names must also differ ignoring case).`);
      }
      names.add(entity.name.toLowerCase());
      result.set(entity.name, entity);
    }
    checkIdentifier(entity.primaryKey, `${label}.primaryKey`, errors);
    if (!Array.isArray(entity.fields) || entity.fields.length === 0) {
      errors.push(`${label}.fields must be a nonempty array.`);
      return;
    }

    const fieldNames = new Set<string>();
    for (const [fieldIndex, field] of entity.fields.entries()) {
      const fieldLabel = `${label}.fields[${fieldIndex}]`;
      if (!isRecord(field)) {
        errors.push(`${fieldLabel} must be an object.`);
        continue;
      }
      checkField(field, fieldLabel, entity.primaryKey, errors);
      if (typeof field.name === "string") {
        if (fieldNames.has(field.name)) {
          errors.push(`${label}: duplicate field name "${field.name}".`);
        }
        fieldNames.add(field.name);
      }
    }
    if (typeof entity.primaryKey === "string" && !fieldNames.has(entity.primaryKey)) {
      errors.push(`Entity "${String(entity.name)}" references unknown primary key: ${entity.primaryKey}.`);
    }
  });

  return result;
}

function checkApis(apis: unknown[], entities: Map<string, RecordValue>, errors: string[]): void {
  const routes = new Set<string>();
  const routePatterns: { method: unknown; segments: string[]; path: string }[] = [];
  const names = new Set<string>();
  const pathPattern = /^\/(?:[A-Za-z0-9_-]+|:[A-Za-z][A-Za-z0-9_]*)(?:\/(?:[A-Za-z0-9_-]+|:[A-Za-z][A-Za-z0-9_]*))*\/?$/;

  apis.forEach((api, index) => {
    const label = `apis[${index}]`;
    if (!isRecord(api)) {
      errors.push(`${label} must be an object.`);
      return;
    }
    checkKeys(api, ["name", "method", "path", "entity", "operation"], label, errors);
    if (!isNonemptyString(api.name)) {
      errors.push(`${label}.name must be a nonempty string without surrounding whitespace.`);
    } else if (names.has(api.name)) {
      errors.push(`${label}: duplicate API name "${api.name}".`);
    } else {
      names.add(api.name);
    }

    const operation = typeof api.operation === "string" && has(operationMethods, api.operation) ? api.operation : undefined;
    if (!operation) {
      errors.push(`${label}.operation must be list, get, create, update, or delete.`);
    }
    if (typeof api.method !== "string" || !["GET", "POST", "PUT", "DELETE"].includes(api.method)) {
      errors.push(`${label}.method must be GET, POST, PUT, or DELETE; PATCH is not supported.`);
    } else if (operation && api.method !== operationMethods[operation]) {
      errors.push(`${label}: operation "${operation}" requires method ${operationMethods[operation]}.`);
    }

    const entity = typeof api.entity === "string" ? entities.get(api.entity) : undefined;
    if (!entity) {
      errors.push(`${label} references unknown entity: ${typeof api.entity === "string" ? api.entity : "entity must be provided"}.`);
    }

    if (typeof api.path !== "string" || !pathPattern.test(api.path)) {
      errors.push(`${label}.path must contain only /static-segments or /:parameter segments; patterns, query strings, and empty segments are not supported.`);
      return;
    }
    const segments = api.path.replace(/\/$/, "").slice(1).split("/");
    const parameters = segments.filter((segment) => segment.startsWith(":")).map((segment) => segment.slice(1));
    if (operation === "get" || operation === "update" || operation === "delete") {
      if (entity && (parameters.length !== 1 || parameters[0] !== entity.primaryKey)) {
        errors.push(`${label}.path must include exactly one parameter :${String(entity.primaryKey)} matching its entity primary key.`);
      }
    } else if (parameters.length > 0) {
      errors.push(`${label}.path cannot contain parameters for list or create operations.`);
    }

    const normalizedPath = `/${segments.map((segment) => segment.startsWith(":") ? ":param" : segment.toLowerCase()).join("/")}`;
    const route = `${String(api.method)} ${normalizedPath}`;
    const normalizedSegments = normalizedPath.slice(1).split("/");
    if (api.method === "GET" && normalizedSegments.length === 1 && ["health", ":param"].includes(normalizedSegments[0])) {
      errors.push(`${label}: GET /health is reserved for the generated health endpoint.`);
    }
    if (routes.has(route)) {
      errors.push(`${label}: duplicate API route ${route} (including equivalent parameter names, case, or trailing slashes).`);
    } else {
      for (const previous of routePatterns) {
        if (previous.method === api.method && previous.segments.length === normalizedSegments.length && previous.segments.every((segment, segmentIndex) => segment === ":param" || normalizedSegments[segmentIndex] === ":param" || segment === normalizedSegments[segmentIndex])) {
          errors.push(`${label}: ambiguous API route ${String(api.method)} ${api.path} overlaps ${previous.path}; use distinct static paths.`);
        }
      }
    }
    routes.add(route);
    routePatterns.push({ method: api.method, segments: normalizedSegments, path: api.path });
  });
}

/** Validate untrusted JSON before any generator writes files. */
export function validateProject(project: unknown): ValidationResult {
  const errors: string[] = [];

  try {
    if (!isRecord(project)) {
      return { valid: false, errors: ["Project definition must be an object."] };
    }
    checkKeys(project, ["name", "version", "entities", "relationships", "apis"], "project", errors);
    if (typeof project.name !== "string" || !/^[A-Za-z0-9][A-Za-z0-9 _-]{0,213}$/.test(project.name) || project.name !== project.name.trim()) {
      errors.push("project.name must be 1–214 letters, digits, spaces, underscores, or hyphens, starting with a letter or digit and without surrounding whitespace.");
    }
    if (typeof project.version !== "string" || !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(project.version)) {
      errors.push("project.version must be a version such as 0.1.0.");
    }

    for (const key of ["entities", "relationships", "apis"]) {
      if (!Array.isArray(project[key])) {
        errors.push(`project.${key} must be an array.`);
      }
    }
    if (Array.isArray(project.entities) && project.entities.length === 0) {
      errors.push("project.entities must contain at least one entity to generate a Prisma client.");
    }
    if (Array.isArray(project.relationships) && project.relationships.length > 0) {
      errors.push("Relationships are not supported yet; project.relationships must be empty.");
    }

    const entities = Array.isArray(project.entities) ? checkEntities(project.entities, errors) : new Map<string, RecordValue>();
    if (Array.isArray(project.apis)) {
      checkApis(project.apis, entities, errors);
    }
  } catch {
    errors.push("Project definition could not be read; provide plain JSON data.");
  }

  return { valid: errors.length === 0, errors };
}
